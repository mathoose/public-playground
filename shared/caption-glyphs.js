function strokeQuad(x0, y0, x1, y1, halfW) {
  const dx = x1 - x0;
  const dy = y1 - y0;
  const len = Math.hypot(dx, dy) || 1;
  const nx = (-dy / len) * halfW;
  const ny = (dx / len) * halfW;
  return [
    [x0 + nx, y0 + ny],
    [x1 + nx, y1 + ny],
    [x1 - nx, y1 - ny],
    [x0 - nx, y0 - ny],
  ];
}

function normalizeChar(ch) {
  if (ch >= "a" && ch <= "z") return ch.toUpperCase();
  return ch;
}

/** Closed polygons for one glyph at (ox, oy) with cap height `h`. */
export function glyphPolys(ch, ox, oy, h, strokeRatio = 0.22) {
  const key = normalizeChar(ch);
  const segs = STROKES[key];
  if (!segs || !segs.length) return [];
  const halfW = (strokeRatio * h) / 2;
  const polys = [];
  for (const [x0, y0, x1, y1] of segs) {
    polys.push(
      strokeQuad(ox + x0 * h, oy + y0 * h, ox + x1 * h, oy + y1 * h, halfW).map(([x, y]) => [x, y])
    );
  }
  return polys;
}

/**
 * Lay out caption text in one line. Returns polygons and total width.
 * @param {string} text
 * @param {{ letterHeight: number, maxWidth: number, tracking?: number }} opts
 */
export function layoutCaptionText(text, opts) {
  const letterH = Math.max(2, opts.letterHeight || 8);
  const maxW = Math.max(letterH, opts.maxWidth || 80);
  const tracking = opts.tracking ?? 0.08;
  const cell = letterH * (0.62 + tracking);
  const raw = String(text || "").slice(0, 48);
  let scale = 1;
  let w = raw.length * cell;
  if (w > maxW && raw.length > 0) scale = maxW / w;
  const h = letterH * scale;
  const c = cell * scale;
  const polys = [];
  let x = -((raw.length * c) / 2);
  for (const ch of raw) {
    polys.push(...glyphPolys(ch, x, -h / 2, h));
    x += c;
  }
  const width = raw.length * c;
  return { polys, width, letterHeight: h, text: raw };
}
